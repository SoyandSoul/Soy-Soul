export function searchAirports(q, limit = 12) {
  const s = q.trim().toLowerCase();
  if (!s) return [];
  return AIRPORTS.filter(a =>
    a.iata.toLowerCase().startsWith(s) || a.icao.toLowerCase().startsWith(s) || a.city.toLowerCase().includes(s)
  ).slice(0, limit);
}
